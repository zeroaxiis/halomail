// newGoogleHTTPClient returns an http.Client equipped with system root CAs plus
// embedded Google Trust Services root certificates as a fallback.
func newGoogleHTTPClient() *http.Client {
	pool, err := x509.SystemCertPool()
	if err != nil || pool == nil {
		pool = x509.NewCertPool()
	}
	pool.AppendCertsFromPEM([]byte(googleRootCAs))
	return &http.Client{
		Timeout: 20 * time.Second,
		Transport: &http.Transport{
			TLSClientConfig: &tls.Config{
				RootCAs: pool,
			},
		},
	}
}

// withGoogleClient returns a context configured with the custom HTTP client for oauth2 calls.
func withGoogleClient(ctx context.Context, httpClient *http.Client) context.Context {
	return context.WithValue(ctx, oauth2.HTTPClient, httpClient)
}

